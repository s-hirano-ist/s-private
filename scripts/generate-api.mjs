import { createApiDocument } from "@s-hirano-ist/s-api-contracts/document";
import { execFileSync } from "node:child_process";
import { mkdir, mkdtemp, readFile, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import ts from "typescript";

function responseContract(status, response, operationId, imports) {
	const json = response.content?.["application/json"];
	if (!json)
		return `${status}: { kind: "${response.content ? "binary" : "empty"}" }`;
	const name = json.schema.$ref?.split("/").at(-1);
	if (!name)
		throw new Error(
			`Name the JSON response schema for ${operationId}:${status}`,
		);
	imports.add(name);
	return `${status}: { kind: "json", schema: ${name} }`;
}
const pnpmCLI = process.env.npm_execpath;
if (!pnpmCLI)
	throw new Error("Run this script using pnpm api:generate or pnpm api:check");
const repoRoot = new URL("../", import.meta.url);
const check = process.argv.includes("--check");
const temporaryDirectory = check
	? await mkdtemp(join(tmpdir(), "s-private-api-"))
	: undefined;
const root = temporaryDirectory
	? pathToFileURL(`${temporaryDirectory}/`)
	: repoRoot;
const document = `${JSON.stringify(createApiDocument(), null, "\t")}\n`;
const specPaths = ["docs/openapi/backend-v1.json"];
for (const path of specPaths) {
	const url = new URL(path, root);
	await mkdir(new URL(".", url), { recursive: true });
	await writeFile(url, document);
}
execFileSync(
	pnpmCLI,
	[
		"exec",
		"oxfmt",
		"--config",
		fileURLToPath(new URL(".oxfmtrc.json", repoRoot)),
		...specPaths.map((path) => fileURLToPath(new URL(path, root))),
	],
	{ cwd: root, stdio: "inherit" },
);

// Only the OpenAPI review snapshot is versioned. Clients are built from the contract.
if (check) {
	try {
		for (const path of specPaths) {
			const expected = await readFile(new URL(path, root));
			const actual = await readFile(new URL(path, repoRoot)).catch(() => null);
			if (!actual || !expected.equals(actual))
				throw new Error(
					`OpenAPI snapshot is stale. Run pnpm api:generate: ${path}`,
				);
		}
	} finally {
		await rm(temporaryDirectory, { recursive: true, force: true });
	}
	process.exit(0);
}

execFileSync(pnpmCLI, ["exec", "orval", "--config", "orval.config.ts"], {
	cwd: repoRoot,
	stdio: "inherit",
	env: { ...process.env, API_GENERATION_ROOT: fileURLToPath(root) },
});

const apiDocument = JSON.parse(document);
const imports = new Set();
const responseRoutes = [];
for (const [path, methods] of Object.entries(apiDocument.paths)) {
	for (const [method, operation] of Object.entries(methods)) {
		const responses = [];
		for (const [status, response] of Object.entries(operation.responses)) {
			responses.push(
				responseContract(status, response, operation.operationId, imports),
			);
		}
		const pattern = path
			.split("/")
			.map((segment) =>
				segment.startsWith("{")
					? "[^/]+"
					: segment.replaceAll(/[.*+?^${}()|[\]\\]/gu, "\\$&"),
			)
			.join("/");
		responseRoutes.push(
			`{ method: "${method.toUpperCase()}", path: new RegExp(${JSON.stringify(`^${pattern}$`)}), responses: { ${responses.join(", ")} } }`,
		);
	}
}
const generatedHeader =
	"// Generated by scripts/generate-api.mjs from the OpenAPI contract. Do not edit.\n";
await writeFile(
	new URL("packages/api-client/src/generated/response-contracts.ts", root),
	`${generatedHeader}import type { ZodType } from "zod";
import { ${[...imports].toSorted().join(", ")} } from "@s-hirano-ist/s-api-client/models";
type ResponseContract = { method: string; path: RegExp; responses: Partial<Record<number, { kind: "json"; schema: ZodType } | { kind: "binary" | "empty" }>> };
export const responseContracts: readonly ResponseContract[] = [${responseRoutes.join(",\n")}];\n`,
);

// Bind the generated fetch argument so consumers cannot accidentally omit validation/authentication.
const source = ts.createSourceFile(
	"backend.ts",
	await readFile(
		new URL("packages/api-client/src/generated/backend.ts", root),
		"utf8",
	),
	ts.ScriptTarget.Latest,
	true,
);
const bindings = [];
for (const statement of source.statements) {
	if (!ts.isVariableStatement(statement)) continue;
	for (const declaration of statement.declarationList.declarations) {
		if (
			!declaration.initializer ||
			!ts.isArrowFunction(declaration.initializer)
		)
			continue;
		const parameters = declaration.initializer.parameters;
		if (parameters.at(-1)?.name.getText(source) !== "fetchFn") continue;
		const name = declaration.name.getText(source);
		const args = parameters
			.slice(0, -1)
			.map(
				(parameter, index) =>
					`${parameter.name.getText(source)}${parameter.questionToken ? "?" : ""}: Parameters<typeof operations.${name}>[${index}]`,
			);
		const calls = parameters.slice(0, -1).map((_, index) => `args[${index}]`);
		const operation = Object.values(apiDocument.paths)
			.flatMap((methods) => Object.values(methods))
			.find((candidate) => candidate.operationId === name);
		const emptySuccess = Object.entries(operation.responses)
			.filter(([status]) => Number(status) >= 200 && Number(status) < 300)
			.every(([, response]) => !response.content);
		const normalize = emptySuccess
			? ".then((result) => ({ ...result, data: undefined }))"
			: "";
		bindings.push(
			`${name}: (...args: [${args.join(", ")}]) => operations.${name}(${[...calls, "fetchFn"].join(", ")})${normalize}`,
		);
	}
}
await writeFile(
	new URL("packages/api-client/src/generated/client.ts", root),
	`${generatedHeader}import * as operations from "@s-hirano-ist/s-api-client/operations";
import { createApiFetch, type ApiTransportOptions } from "@s-hirano-ist/s-api-client/transport";
export function createBackendClient(options: ApiTransportOptions) {
 const fetchFn = createApiFetch(options);
 return { ${bindings.join(",\n")} };
}\n`,
);
